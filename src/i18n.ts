const LOCALE_KEY = 'depthvideo-locale';

let current: Lang = (() => {
  try {
    const saved = localStorage.getItem(LOCALE_KEY);
    if (saved === 'zh' || saved === 'en') return saved;
  } catch {
    /* localStorage 不可用时走探测 */
  }
  return navigator.language.toLowerCase().startsWith('zh') ? 'zh' : 'en';
})();

export function getLang(): Lang {
  return current;
}

/** 取值：当前语言 → zh 兜底 → key 本身；{param} 插值（原站 Z 函数） */
export function t(key: string, params?: Record<string, string | number>): string {
  let s = DICTS[current][key] ?? DICTS.zh[key] ?? key;
  if (params) {
    for (const [k, v] of Object.entries(params)) s = s.replaceAll(`{${k}}`, String(v));
  }
  return s;
}

export function setLang(lang: Lang): void {
  current = lang;
  try {
    localStorage.setItem(LOCALE_KEY, lang);
  } catch {
    /* 持久化失败不阻塞切换 */
  }
  document.documentElement.lang = lang === 'zh' ? 'zh-CN' : 'en';
}

/** 刷新 DOM 中所有 data-i18n* 属性（原站 NH 函数） */
export function applyI18n(root: ParentNode = document): void {
  root.querySelectorAll<HTMLElement>('[data-i18n]').forEach((el) => {
    const key = el.dataset.i18n;
    if (key) el.textContent = t(key);
  });
  root.querySelectorAll<HTMLElement>('[data-i18n-html]').forEach((el) => {
    const key = el.dataset.i18nHtml;
    if (key) el.innerHTML = t(key);
  });
  root.querySelectorAll<HTMLElement>('[data-i18n-aria]').forEach((el) => {
    const key = el.dataset.i18nAria;
    if (key) el.setAttribute('aria-label', t(key));
  });
  root.querySelectorAll<HTMLElement>('[data-i18n-title]').forEach((el) => {
    const key = el.dataset.i18nTitle;
    if (key) el.title = t(key);
  });
}

/** 刷新 document.title 与 description / og / twitter / og:locale meta（原站 PH 函数） */
export function applyDocMeta(): void {
  document.title = t('doc.title');
  const set = (selector: string, content: string) => {
    document.querySelector(selector)?.setAttribute('content', content);
  };
  set('meta[name="description"]', t('doc.description'));
  set('meta[property="og:title"]', t('doc.title'));
  set('meta[property="og:description"]', t('doc.description'));
  set('meta[name="twitter:title"]', t('doc.title'));
  set('meta[name="twitter:description"]', t('doc.description'));
  set('meta[property="og:locale"]', current === 'zh' ? 'zh_CN' : 'en_US');
}

/** 刷新语言按钮激活态与 aria-pressed（原站 BW 函数） */
export function syncLangButtons(): void {
  document.querySelectorAll<HTMLButtonElement>('.lang-btn').forEach((btn) => {
    const active = btn.dataset.lang === current;
    btn.classList.toggle('is-active', active);
    btn.setAttribute('aria-pressed', active ? 'true' : 'false');
  });
}
